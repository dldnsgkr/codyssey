"""
이 파일은 해당 디렉토리를 Python 패키지로 인식시키기 위해 생성된다.

📌 왜 __init__.py가 필요한가?
Python에서 디렉토리를 모듈처럼 import 하기 위해서는
해당 폴더가 "패키지"라는 것을 명시해야 한다.
__init__.py 파일이 존재하면 Python은 이 폴더를 패키지로 인식하고,
다른 파일에서 import 문을 통해 접근할 수 있게 된다.

예:
from problem_3.mars_mission_computer import DummySensor

이와 같은 import가 가능해지는 이유가 바로 __init__.py 때문이다.

---

📌 __pycache__는 왜 생성되는가?
Python은 .py 파일을 실행할 때 내부적으로 바이트코드(.pyc)로 변환하여 실행한다.
이 변환된 파일을 저장하는 폴더가 __pycache__이다.

---

📌 __pycache__의 역할
- 실행 속도를 향상시키기 위해 사용된다.
- 동일한 코드를 다시 실행할 때, 이미 변환된 .pyc 파일을 재사용한다.
- 개발자가 직접 관리할 필요는 없다.

---

📌 주의사항
- __pycache__ 폴더는 자동 생성되며, 삭제해도 문제없다.
- Git과 같은 버전 관리 시스템에는 포함하지 않는 것이 일반적이다.
"""